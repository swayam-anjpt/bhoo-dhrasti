/**
 * Calculate dynamic composite score based on customizable weights
 */
export function calculateWeightedTemporalScore(
  envScore: number,
  accScore: number,
  popScore: number,
  urbScore: number,
  weights: TemporalDimensionWeights = DEFAULT_TEMPORAL_WEIGHTS
): number {
  const totalWeight = weights.environment + weights.accessibility + weights.population + weights.urbanization;
  if (totalWeight <= 0) return 0;
  
  const score = (
    envScore * weights.environment +
    accScore * weights.accessibility +
    popScore * weights.population +
    urbScore * weights.urbanization
  ) / totalWeight;
  
  return Number(score.toFixed(1));
}

/**
 * Calculate temporal comparison between any two years
 */
export function calculateTemporalComparison(
  fromYear: TemporalYear,
  toYear: TemporalYear,
  summary: DistrictTemporalSummary = AHMEDABAD_DISTRICT_TEMPORAL_SUMMARY
): TemporalComparisonResult {
  const from = summary.yearlySummaries[fromYear];
  const to = summary.yearlySummaries[toYear];
  
  const overallDelta = Number((to.overallDevelopmentScore - from.overallDevelopmentScore).toFixed(1));
  const overallDeltaPercent = Number((((to.overallDevelopmentScore - from.overallDevelopmentScore) / from.overallDevelopmentScore) * 100).toFixed(1));
  
  const envDelta = Number((to.environmentalScore - from.environmentalScore).toFixed(1));
  const accDelta = Number((to.accessibilityScore - from.accessibilityScore).toFixed(1));
  const popDelta = Number((to.populationPressureScore - from.populationPressureScore).toFixed(1));
  const urbDelta = Number((to.urbanizationScore - from.urbanizationScore).toFixed(1));
  
  return {
    fromYear,
    toYear,
    overallDelta,
    overallDeltaPercent,
    environmentalDelta: envDelta,
    accessibilityDelta: accDelta,
    populationDelta: popDelta,
    urbanizationDelta: urbDelta,
    dimensionComparison: [
      {
        dimension: 'Environmental Quality',
        fromValue: from.environmentalScore,
        toValue: to.environmentalScore,
        delta: envDelta,
        deltaPercent: Number((((to.environmentalScore - from.environmentalScore) / from.environmentalScore) * 100).toFixed(1)),
        status: envDelta >= 0 ? 'improved' : Math.abs(envDelta) < 3 ? 'stable' : 'deteriorated',
      },
      {
        dimension: 'Citizen Accessibility',
        fromValue: from.accessibilityScore,
        toValue: to.accessibilityScore,
        delta: accDelta,
        deltaPercent: Number((((to.accessibilityScore - from.accessibilityScore) / from.accessibilityScore) * 100).toFixed(1)),
        status: accDelta > 0 ? 'improved' : accDelta === 0 ? 'stable' : 'deteriorated',
      },
      {
        dimension: 'Population Pressure',
        fromValue: from.populationPressureScore,
        toValue: to.populationPressureScore,
        delta: popDelta,
        deltaPercent: Number((((to.populationPressureScore - from.populationPressureScore) / from.populationPressureScore) * 100).toFixed(1)),
        status: popDelta > 0 ? 'improved' : 'stable',
      },
      {
        dimension: 'Urbanization Level',
        fromValue: from.urbanizationScore,
        toValue: to.urbanizationScore,
        delta: urbDelta,
        deltaPercent: Number((((to.urbanizationScore - from.urbanizationScore) / from.urbanizationScore) * 100).toFixed(1)),
        status: urbDelta > 0 ? 'improved' : 'stable',
      },
    ],
  };
}

